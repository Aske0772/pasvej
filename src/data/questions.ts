const EDITION = '2026-08' as const

interface Opts {
  /** Keep options in the given order (Ja/Nej, years, percentages), as the exam does. */
  fixed?: boolean
}

function q(
  id: string,
  topic: string,
  source: string,
  prompt: string,
  options: string[],
  answer: number,
  da: string,
  en: string,
  opts: Opts = {},
): Question {
  return {
    id,
    exam: 'indfodsret',
    topic,
    prompt,
    options,
    answer,
    explain: { da, en },
    source,
    edition: topicById(topic).section === 'material' ? EDITION : null,
    ...(opts.fixed ? { fixedOrder: true } : {}),
  }
}

/** Ordered options such as years or percentages. */
const ordered = (id: string, topic: string, source: string, prompt: string, options: string[], answer: number, da: string, en: string) =>
  q(id, topic, source, prompt, options, answer, da, en, { fixed: true })

/** Ja/Nej question. */
const yn = (id: string, topic: string, source: string, prompt: string, yes: boolean, da: string, en: string) =>
  q(id, topic, source, prompt, ['Ja', 'Nej'], yes ? 0 : 1, da, en, { fixed: true })

